package com.mountaya.geo

/**
 * timeZoneViewport is the viewport a map opens on for a reader in [timeZone], an IANA time zone
 * name such as `Europe/Zurich`, or null where the table answers none.
 *
 * The zone is an argument, never a read of the ambient zone: a probe of the environment is not a
 * geographic fact, and a table is only worth having if it can be checked without one. A zone is
 * read under the name a runtime reports for it as well as under its own: an older spelling the tz
 * database keeps as a link (`Asia/Calcutta` for `Asia/Kolkata`), and a zone it merged into a
 * neighbour, which answers the zone that holds it today (`America/Montreal` answers
 * `America/Toronto`). A name is matched exactly, letter case included.
 *
 * The table is the contract's, `geo/timezone-viewport.json`'s `zoneViewports` and
 * `reportedZoneNames` value for value, and answers no viewport for any other name: a link no runtime reports (`US/Pacific`), a zone of no country (`Etc/UTC`, an Antarctic
 * station) and a name that is no zone answer null, and Macquarie Island, filed under Antarctica,
 * answers Australia's.
 */
public fun timeZoneViewport(timeZone: String): MapViewport? {
    val zone = reportedZoneNames[timeZone] ?: timeZone
    return zoneViewports[zone]
}

